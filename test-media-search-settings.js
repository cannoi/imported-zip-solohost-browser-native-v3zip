const fs = require('fs');
const assert = require('assert');
const pkg = require('./package.json');
const caps = require('./lib/engine/capabilities').detect();
const adapter = require('./lib/app-adapter');
const html = fs.readFileSync('public/index.html','utf8');
const app = fs.readFileSync('public/app.js','utf8');
const server = fs.readFileSync('server-app.js','utf8');
const bridge = fs.readFileSync('lib/engine/dom-bridge.js','utf8');
assert.strictEqual(pkg.version, '10.25.0');
assert.strictEqual(caps.version, pkg.version);
assert(html.includes('id="btn-search-settings"'), 'search engine settings entry exists');
for (const id of ['search-engine-select','search-engine-custom','search-settings-save']) assert(html.includes('id="'+id+'"'), 'search setting control ' + id);
for (const engine of ['bing','google','duckduckgo','brave','custom']) assert(html.includes('value="'+engine+'"'), 'engine option ' + engine);
assert(app.includes('buildSearchUrl(query)'), 'query uses configured search URL builder');
assert(app.includes('solo_search_engine') && app.includes('solo_search_custom_url'), 'search setting persists in browser profile');
assert(app.includes('template.replace(/\\{query\\}/gi, encoded).replace(/%s/gi, encoded)'), 'custom URL placeholders replaced with encoded query');
assert(app.includes('isNativeMediaOrDocumentUrl'), 'native media/document URLs use native browser viewer');
assert(app.includes('if (isNativeMediaOrDocumentUrl(abs))'), 'clicking direct media/document links enters native viewer mode');
assert(app.includes('if (isDirectEmbed(url)) return MODE.DIRECT'), 'official YouTube/TikTok/Vimeo embed URLs use direct player mode');
for (const host of ['www.youtube.com','www.tiktok.com','player.vimeo.com','open.spotify.com','player.twitch.tv','www.dailymotion.com']) assert(server.includes('https://'+host), 'CSP allows official media host '+host);
assert(bridge.includes("host === 'tiktok.com' || host.endsWith('.tiktok.com')"), 'TikTok official embeds retained by sanitizer');
const knowledge = adapter.knowledge;
assert(knowledge.includes('RUNTIME VERSION: '+pkg.version), 'AI knowledge uses installed package version');
assert(knowledge.includes('Default Search Engine') && knowledge.includes('Custom URL'), 'AI kernel knows current search settings');
assert(knowledge.includes('TikTok') && knowledge.includes('Spotify'), 'AI kernel knows media capabilities');
assert(knowledge.includes('Google/Bing verification challenges are not bypassed'), 'AI knowledge accurately states verification limitation');
console.log('Media / search settings / runtime AI knowledge regression: PASS');
