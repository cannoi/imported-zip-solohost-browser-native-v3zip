'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const backend = require('./lib/backend-agent');
const html = `<!doctype html><html><head><style>body{color:red}</style></head><body><h1>News &amp; Updates</h1><a data-sh-id="e2" href="https://example.com/news">Read story</a><input data-sh-id="e3" type="text" placeholder="Search" value="news"><input data-sh-id="e4" type="password" placeholder="Password"><button data-sh-id="e5">Search</button><script>document.body.innerHTML='pwned'</script></body></html>`;
const obs = backend.observeSession({ html, url: 'https://example.com/', title: 'Example', audit: { textLength: 15, controls: 3 } });
assert.match(obs.text, /News & Updates/);
assert.ok(obs.elements.some(e => e.tag === 'a' && e.href === 'https://example.com/news'));
assert.ok(obs.elements.some(e => e.tag === 'input' && /secret field/.test(e.label)));
assert.strictEqual(obs.elements.find(e => e.label === 'Search').value, 'news');
assert.ok(Object.keys(obs.targets).length >= 3);
const client = fs.readFileSync(path.join(__dirname, 'public/browser-agent.js'), 'utf8');
assert.ok(client.includes('/api/browser/agent/tasks'));
assert.ok(!client.includes('contentDocument'), 'UI agent must not inspect iframe DOM');
assert.ok(!client.includes('el.click()'), 'UI agent must not execute page clicks');
const server = fs.readFileSync(path.join(__dirname, 'server.js'), 'utf8');
assert.ok(server.includes('/api/browser/agent/sessions/:sessionId/tasks/:taskId/confirm'));
const panel = fs.readFileSync(path.join(__dirname, 'public/ai-panel.js'), 'utf8');
assert.ok(!panel.includes('onActions: executeActions') && !panel.includes('function executeActions('), 'AI actions must not be dispatched twice');
console.log('Backend Browser Agent tests PASS');
