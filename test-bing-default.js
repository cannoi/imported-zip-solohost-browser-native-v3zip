
'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = __dirname;
const app = fs.readFileSync(path.join(root, 'public/app.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'public/index.html'), 'utf8');
const serverApp = fs.readFileSync(path.join(root, 'server-app.js'), 'utf8');
const agent = fs.readFileSync(path.join(root, 'lib/browser-agent.js'), 'utf8');
const backendAgent = fs.readFileSync(path.join(root, 'lib/backend-agent.js'), 'utf8');
const aiAgent = fs.readFileSync(path.join(root, 'lib/ai-agent.js'), 'utf8');
const bridge = fs.readFileSync(path.join(root, 'lib/engine/dom-bridge.js'), 'utf8');
const proxy = fs.readFileSync(path.join(root, 'lib/frame-proxy.js'), 'utf8');
const templates = fs.readFileSync(path.join(root, 'lib/engine/layout-templates.js'), 'utf8');
const pkg = require('./package.json');
const caps = require('./lib/engine/capabilities').detect();
const proxyApi = require('./lib/frame-proxy');
assert.strictEqual(pkg.version, '10.25.20');
assert.strictEqual(caps.version, '10.25.20');
assert.ok(app.includes("return 'https://www.bing.com/search?q=' + encoded") && app.includes("searchEngine: (typeof localStorage !== 'undefined' && localStorage.getItem('solo_search_engine')) || 'bing'"), 'Bing remains the default while user-selected engines are supported');
assert.ok(html.includes('placeholder="Search Bing or enter address"'), 'omnibox must communicate Bing default');
assert.ok(serverApp.includes("req.query.engine || 'bing'") && serverApp.includes("engine === 'bing'"), 'server quick search defaults to Bing');
assert.ok(agent.includes("engine: 'ddg', query: m[1].trim()"), 'agent uses DDG for generic searches to reduce repeated Google verification; browser UI still defaults to Bing');
assert.ok(backendAgent.includes("'https://www.bing.com/search?q=' + q"), 'backend agent default search URL must be Bing');
assert.ok(aiAgent.includes('https://www.bing.com/search?q=QUERY'), 'AI navigation guidance must use Bing');
assert.ok(bridge.includes('isBingUrl') && templates.includes('#b_content') && templates.includes('.b_algo'), 'Bing responsive styles exist in page-family templates');
assert.ok(bridge.includes('safeGoogleSearchQuery') && bridge.includes('^EgQ[A-Za-z0-9_-]{12,}$'), 'Google fallback rejects challenge-token queries');
assert.ok(proxy.includes('safeGoogleSearchQuery(doc.finalUrl || normalized)'), 'proxy challenge fallback uses safe query extraction');
assert.strictEqual(proxyApi.safeGoogleSearchQuery('https://www.google.com/search?q=phim+hay'), 'phim hay', 'real Google search query is preserved');
assert.strictEqual(proxyApi.safeGoogleSearchQuery('https://www.google.com/sorry/index?q=EgQOsE4uGIm-rdYGIjDCRlbQJyquQt682lJAg4DD2i9KmAUi'), '', 'challenge token is not a search query');
assert.strictEqual(proxyApi.safeGoogleSearchQuery('https://www.google.com/sorry/index?continue=https%3A%2F%2Fwww.google.com%2Fsearch%3Fq%3Dphim%2Bhay'), 'phim hay', 'safe query can be recovered from search continuation');
assert.ok(bridge.includes('bridge.google_login_rejected'), 'Google login rejection gets a distinct diagnostic log');
console.log('✓ Bing default, responsive Bridge, safe Google fallback and login diagnostics');
