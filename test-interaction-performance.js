'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = __dirname;
const engine = fs.readFileSync(path.join(root, 'lib/engine/playwright-engine.js'), 'utf8');
const app = fs.readFileSync(path.join(root, 'public/app.js'), 'utf8');
const bridge = require('./lib/engine/dom-bridge');
const pkg = require('./package.json');
const caps = require('./lib/engine/capabilities').detect();
assert.strictEqual(pkg.version, '10.31.1');
assert.strictEqual(caps.version, '10.31.1');
assert.ok(engine.includes('const dispatchQueues = new Map()'), 'engine events are serialized per session');
assert.ok(engine.includes("['checkbox', 'radio'].includes(meta.type)"), 'checkbox and radio controls have native state handling');
assert.ok(engine.includes("meta.tag === 'select'"), 'select controls use selectOption');
assert.ok(engine.includes('el.isContentEditable'), 'contenteditable text fields are supported');
assert.ok(engine.includes("const sel = 'a,button,input,select,textarea,form,label,"), 'labels and semantic role controls receive bridge IDs');
assert.ok(engine.includes("type === 'document' || type === 'script' || type === 'xhr' || type === 'fetch'"), 'documents, scripts, and application data bypass cosmetic resource filtering');
assert.ok(engine.includes('isAdOrTrackerRequest(url)'), 'known ad/tracker requests use the lightweight filter');
assert.ok(app.includes('const bridgeAuditSeen = new Set()'), 'repeat audits are deduplicated');
assert.ok(app.includes("(el.isContentEditable || el.getAttribute('role') === 'textbox') ? el.innerText : el.value"), 'contenteditable values are forwarded');
assert.strictEqual(bridge.isBingVerification({ verificationChallenge: true, url: 'https://www.bing.com/search?q=test' }, 'https://www.bing.com/search?q=test'), true);
assert.strictEqual(bridge.isBingVerification({ verificationChallenge: true }, 'https://example.com/'), false);
assert.strictEqual(bridge.isBingVerification({ html: '<p>Please solve the challenge below to continue</p>' }, 'https://www.bing.com/search?q=test'), true);
assert.strictEqual(bridge.isBingVerification({ html: '<p>Please solve the challenge below to continue</p>' }, 'https://example.com/'), false);
console.log('✓ responsive bridge events, form controls, Bing resource compatibility and verification handoff');
