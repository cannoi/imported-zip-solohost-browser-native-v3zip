'use strict';
const assert = require('assert');
const fs = require('fs');
const pkg = require('./package.json');
const html = fs.readFileSync('public/index.html', 'utf8');
const app = fs.readFileSync('public/app.js', 'utf8');
const css = fs.readFileSync('public/style.css', 'utf8');
const panel = fs.readFileSync('public/ai-panel.js', 'utf8');
const adapter = require('./lib/app-adapter');
assert.strictEqual(pkg.version, '10.25.25');
assert.strictEqual(panel.includes("version: '10.25.25'"), true, 'AI panel version is current');
assert(html.includes('id="bg-music-audio"') && html.includes('controls'), 'native audio player exists in UI');
assert(app.includes('function isDirectAudioUrl(raw)') && /mp3\|m4a\|aac\|wav\|flac\|opus\|oga\|ogg/.test(app), 'direct audio URLs have a narrow HTTP(S) file-extension detector');
assert(app.includes("clientLog('info', 'playlist.direct_audio_play'") && app.includes("clientLog('warn', 'playlist.direct_audio_error'"), 'native playback logs success-path selection and errors');
assert(app.includes("directAudio.addEventListener('ended'") && app.includes("$('bg-music-next').addEventListener"), 'audio end and next/previous controls are wired');
assert(css.includes('.bg-music-dock .bg-music-audio'), 'dock audio player is styled responsively');
assert(adapter.knowledge.includes('client-native playback'), 'AI Kernel knows the client-native audio path');
assert(adapter.knowledge.includes('Backend Chromium/system audio capture and streaming to the UI') && adapter.knowledge.includes('are NOT implemented'), 'AI Kernel clearly discloses backend stream limitation');
assert(adapter.knowledge.includes('autoplay policy/codecs/server headers'), 'AI Kernel knows playback constraints');
console.log('v10.25.0 client-native audio / AI knowledge regression: PASS');
