'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = __dirname;
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const engine = read('lib/engine/playwright-engine.js');
const app = read('public/app.js');
const caps = read('lib/engine/capabilities.js');
const pipeline = read('lib/engine/content-pipeline.js');
const proxy = read('lib/frame-proxy.js');
const adapter = read('lib/app-adapter.js');
const readme = read('README.md');
const pkg = JSON.parse(read('package.json'));

assert.strictEqual(pkg.version, '10.25.20', 'version is bumped');
assert(engine.includes("openerPage.on('popup'"), 'popup handler belongs to opener page');
assert(!engine.includes("state.context.on('page'"), 'no per-session shared-context page listener');
assert(engine.includes('findUnownedPage(s.context, s) || await s.context.newPage()'), 'recovery must not steal context.pages()[0]');
assert(engine.includes('findUnownedPage(context, null)'), 'new tab reuses only an unowned page');
assert(engine.includes('browser_page_limit_reached'), 'page cap reports a clear error');
assert(engine.includes('Number(process.env.SOLOHOST_PW_MAX_SESSIONS) || 12'), 'Chromium session cap matches the 12-tab UI');
assert(read('lib/engine/dom-bridge.js').includes('Number(process.env.SOLOHOST_BRIDGE_MAX_SESSIONS) || 12'), 'Bridge session cap matches Chromium and the 12-tab UI');
assert(app.includes('state.activeTabId !== tab.id'), 'late bridge responses cannot overwrite active tab');
assert(app.includes('frame.getAttribute(\'data-sh-tab-id\') !== String(state.activeTabId || \'\')'), 'stale iframe events are ignored');
assert(app.includes("String(aEl.getAttribute('target') || '').toLowerCase() === '_blank'"), 'target=_blank opens a SoloHost tab');
assert(app.includes("/^(javascript|data|blob):/i.test(hrefRaw)"), 'unsafe schemes are not navigated');
assert(app.includes("d.type === 'solohost-open-external'"), 'mailto/tel links use an explicit external-protocol handler');
assert(proxy.includes('data-sh-open-new-tab'), 'proxy-rendered target=_blank links preserve new-tab intent');
assert(proxy.includes('function tellExternal(url)'), 'proxy-rendered mailto/tel links are routed to the host');
assert(!caps.includes('staticCapture'), 'Static Capture capability removed');
assert(!engine.includes('createCapturePage'), 'auxiliary Static Capture API removed');
assert(!adapter.includes('Static Capture uses'), 'AI knowledge no longer advertises removed feature');
assert(!readme.includes('/static-capture.html'), 'README no longer links removed UI');
assert(pipeline.includes('Shared live-page extraction pipeline for the SoloHost Bridge'), 'shared extraction remains for Bridge');
assert(!pipeline.includes('extractReadable') && !pipeline.includes('@mozilla/readability') && !pipeline.includes('jsdom'), 'unused static-export extraction stack removed');
assert(!read('Dockerfile').includes("require('archiver')"), 'Docker dependency check no longer requires an absent static-export package');
assert(!('jsdom' in pkg.dependencies) && !('@mozilla/readability' in pkg.dependencies), 'unused static-export dependencies removed');
console.log('v10.25.20 tab synchronization / Static Capture removal regression: PASS');
