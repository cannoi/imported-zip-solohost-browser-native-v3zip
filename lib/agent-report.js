'use strict';
/**
 * Build a full static-friendly agent completion report from task state.
 * No aggressive truncation of the final user-facing answer.
 */

function clip(s, n) {
  s = String(s || '');
  if (s.length <= n) return s;
  return s.slice(0, n) + '…';
}

function uniq(arr) {
  const out = [];
  const seen = new Set();
  for (const x of arr) {
    const k = String(x || '').trim();
    if (!k || seen.has(k)) continue;
    seen.add(k);
    out.push(k);
  }
  return out;
}

function extractUrls(text) {
  const re = /https?:\/\/[^\s\]\)"'<>]+/gi;
  const found = String(text || '').match(re) || [];
  return uniq(found.map((u) => u.replace(/[.,;:]+$/, '')));
}

function isMediaUrl(u) {
  return /\.(png|jpe?g|gif|webp|svg|mp4|webm|m3u8|mp3|ogg|pdf)(\?|$)/i.test(u) ||
    /youtube\.com\/watch|youtu\.be\/|vimeo\.com\//i.test(u);
}

/**
 * @param {object} task
 * @returns {{ markdown: string, htmlSections: object, links: string[], media: string[], steps: array }}
 */
function buildAgentReport(task) {
  const lang = task.lang === 'vi' ? 'vi' : 'en';
  const wm = task.workMemory || {};
  const history = Array.isArray(task.history) ? task.history : [];
  const summaryRaw =
    task.message ||
    (task.lastDoneSummary) ||
    (lang === 'vi' ? 'Nhiệm vụ đã hoàn thành.' : 'Task completed.');

  const findings = [];
  (wm.findings || []).forEach((f) => {
    if (typeof f === 'string') findings.push(f);
    else if (f && (f.fact || f.text)) findings.push((f.fact || f.text) + (f.url ? ' — ' + f.url : ''));
  });
  (wm.notes || []).forEach((n) => findings.push(String(n)));

  const stepLines = history.map((h, i) => {
    const n = h.step || i + 1;
    const thought = h.thought || h.text || '';
    const act = h.action ? (h.action.type || '') + (h.action.url ? ' ' + h.action.url : '') + (h.action.query ? ' ' + h.action.query : '') : '';
    return { n, thought, action: act, url: h.url || (h.action && h.action.url) || '' };
  });

  const visited = uniq([].concat(wm.visited || [], stepLines.map((s) => s.url).filter(Boolean)));
  const allText = [summaryRaw, findings.join('\n'), stepLines.map((s) => s.thought + ' ' + s.action).join('\n'), visited.join('\n')].join('\n');
  const links = extractUrls(allText);
  const media = links.filter(isMediaUrl);
  const refs = links.filter((u) => !isMediaUrl(u));

  const title = lang === 'vi' ? 'Báo cáo hoàn thành Agent' : 'Agent completion report';
  const lines = [];
  lines.push('# ' + title);
  lines.push('');
  lines.push(lang === 'vi' ? '## Tóm tắt kết quả' : '## Result summary');
  lines.push(String(summaryRaw).trim());
  lines.push('');
  if (findings.length) {
    lines.push(lang === 'vi' ? '## Phát hiện / dữ liệu thu thập' : '## Findings');
    findings.slice(0, 80).forEach((f, i) => lines.push((i + 1) + '. ' + f));
    lines.push('');
  }
  if (stepLines.length) {
    lines.push(lang === 'vi' ? '## Các bước đã thực hiện' : '## Steps taken');
    stepLines.slice(-40).forEach((s) => {
      lines.push(s.n + '. ' + (s.action || s.thought || 'step') + (s.url ? ' — ' + s.url : ''));
      if (s.thought && s.action) lines.push('   ' + clip(s.thought, 400));
    });
    lines.push('');
  }
  if (refs.length) {
    lines.push(lang === 'vi' ? '## Nguồn & liên kết tham chiếu' : '## Sources & reference links');
    refs.slice(0, 60).forEach((u, i) => lines.push((i + 1) + '. ' + u));
    lines.push('');
  }
  if (media.length) {
    lines.push(lang === 'vi' ? '## Ảnh / media' : '## Media');
    media.slice(0, 40).forEach((u, i) => lines.push((i + 1) + '. ' + u));
    lines.push('');
  }
  if (visited.length) {
    lines.push(lang === 'vi' ? '## Trang đã mở' : '## Pages visited');
    visited.slice(0, 40).forEach((u, i) => lines.push((i + 1) + '. ' + u));
    lines.push('');
  }
  lines.push(lang === 'vi'
    ? '_Báo cáo tự động từ SoloHost Browser Agent. Kiểm tra lại liên kết trước khi dùng._'
    : '_Auto-generated by SoloHost Browser Agent. Verify links before use._');

  const markdown = lines.join('\n');
  return {
    markdown,
    summary: summaryRaw,
    findings: findings.slice(0, 80),
    steps: stepLines.slice(-40),
    links: refs.slice(0, 60),
    media: media.slice(0, 40),
    visited: visited.slice(0, 40),
    task: clip(task.task || '', 2000),
    generatedAt: new Date().toISOString()
  };
}

/** Ensure done payload is long enough; merge workMemory if summary is too short. */
function finalizeDoneMessage(task, summary) {
  let msg = String(summary || task.message || '').trim();
  const report = buildAgentReport(Object.assign({}, task, { message: msg, lastDoneSummary: msg }));
  // If model only said "Done." expand to full report
  if (msg.length < 80 || /^(done\.?|xong\.?|hoàn thành\.?|completed\.?)$/i.test(msg)) {
    msg = report.markdown;
  } else if (!/https?:\/\//i.test(msg) && (report.links.length || report.findings.length > 2)) {
    // Append structured appendix so user still gets sources
    msg = msg + '\n\n---\n' + report.markdown.split('\n').slice(2).join('\n');
  }
  // Hard cap for transport only (very large reports)
  if (msg.length > 120000) msg = msg.slice(0, 120000) + '\n…';
  return { message: msg, report };
}

module.exports = { buildAgentReport, finalizeDoneMessage, extractUrls };
