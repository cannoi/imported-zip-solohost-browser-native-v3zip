'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const engine = fs.readFileSync(path.join(__dirname, 'lib/engine/playwright-engine.js'), 'utf8');
const bridge = fs.readFileSync(path.join(__dirname, 'lib/engine/dom-bridge.js'), 'utf8');
const pkg = require('./package.json');
assert.strictEqual(pkg.version, '10.25.22');
const start = engine.indexOf('async function markInteractive(page)');
const end = engine.indexOf('\nasync function navigate(', start);
assert(start >= 0 && end > start, 'legacy markInteractive extraction function exists');
const snapshot = engine.slice(start, end);
assert(snapshot.includes('document.documentElement.cloneNode(true)'), 'snapshot clones the live DOM document');
assert(snapshot.includes("drop('script, noscript, template')"), 'active scripts are omitted from display snapshot while live Chromium continues running');
assert(snapshot.includes("drop('object, embed')"), 'legacy renderer removes plugin objects');
assert(snapshot.includes('solohost-adaptive-layout'), 'legacy snapshot keeps the conservative responsive stylesheet');
assert(!snapshot.includes('hasSearch && resultBlocks'), 'post-v10.20 DOM-signal family classifier is not used');
assert(!snapshot.includes('cloudflare') && !snapshot.includes('googleSorry'), 'post-v10.20 challenge expansion is not injected into legacy extraction');
assert(!bridge.includes('const routeHint = contentRouter.classify(safeBase'), 'sanitizer does not inject the newer family-template marker');
assert(bridge.includes('target="_self" data-sh-nav="1"'), 'current safe SoloHost link routing is retained');
assert(bridge.includes('safeBase'), 'validated base URL hardening is retained');
assert(engine.includes("openerPage.on('popup'"), 'tab-safe popup handling is retained');
assert(engine.includes('findUnownedPage'), 'session recovery does not steal another tab page');
console.log('v10.25.22 legacy v10.20.0 extraction/presentation regression: PASS');
