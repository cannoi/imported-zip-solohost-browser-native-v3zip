'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = __dirname;
const engineSource = fs.readFileSync(path.join(root, 'lib/engine/playwright-engine.js'), 'utf8');
const bridgeSource = fs.readFileSync(path.join(root, 'lib/engine/dom-bridge.js'), 'utf8');
const pkg = require('./package.json');
const bridge = require('./lib/engine/dom-bridge');
const engine = require('./lib/engine/playwright-engine');
assert.strictEqual(pkg.version, '10.11.0');
assert.ok(engineSource.includes('focusedMode'), 'focused mode is passed safely into page evaluation');
assert.ok(engineSource.includes('solohost-focused-mode'), 'snapshot receives compact readable styling');
assert.ok(engineSource.includes('animation:none!important') && engineSource.includes('transition:none!important'), 'snapshot suppresses animations and transitions');
assert.ok(engineSource.includes('[data-ad]') && engineSource.includes('sponsored-content'), 'known ad markers are removed conservatively');
assert.ok(engineSource.includes("setAttribute('loading', 'lazy')"), 'snapshot images are lazy-loaded');
assert.ok(engineSource.includes("context.route"), "known third-party ad/tracker hosts can be blocked before loading");
assert.ok(engineSource.includes("reducedMotion: 'reduce'"), 'engine requests reduced motion preference');
assert.ok(engineSource.includes('data-sh-media-placeholder'), 'heavy media is replaced with lightweight placeholders');
assert.ok(engineSource.includes('Animated image omitted'), 'animated GIFs are not rendered as looping motion in focused mode');
assert.ok(engineSource.includes('SOLOHOST_BROWSER_CONTENT_MODE'), 'focused display mode can be configured');
const sample = 'https://snssdk1180.onelink.me/BAuo?domain_source=tiktok&canonical=https%3A%2F%2Fwww.tiktok.com%2Fdiscover%2Fdance-categories&pid=tiktokwebseo';
assert.strictEqual(bridge.normalizeKnownLandingUrl(sample), 'https://www.tiktok.com/discover/dance-categories');
const malicious = 'https://example.onelink.me/path?domain_source=tiktok&canonical=https%3A%2F%2Fevil.example%2Fsteal';
assert.strictEqual(bridge.normalizeKnownLandingUrl(malicious), malicious, 'untrusted canonical hosts are not followed');
const normal = 'https://www.tiktok.com/@user/video/123';
assert.strictEqual(bridge.normalizeKnownLandingUrl(normal), normal, 'ordinary site URLs are unchanged');
assert.strictEqual(engine.isAdOrTrackerRequest('https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js'), true);
assert.strictEqual(engine.isAdOrTrackerRequest('https://www.tiktok.com/api/post/item_list/'), false, 'first-party content APIs remain available');
assert.strictEqual(engine.isAdOrTrackerRequest('https://example.com/article'), false, 'ordinary page requests remain available');
console.log('✓ focused content mode, conservative ad/media reduction, and TikTok landing URL normalization');
