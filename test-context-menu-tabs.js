const fs = require('fs');
const assert = require('assert');
const app = fs.readFileSync('public/app.js', 'utf8');
const html = fs.readFileSync('public/index.html', 'utf8');
const css = fs.readFileSync('public/style.css', 'utf8');
const server = fs.readFileSync('server-app.js', 'utf8');
const bridge = fs.readFileSync('lib/engine/dom-bridge.js', 'utf8');
const engine = fs.readFileSync('lib/engine/playwright-engine.js', 'utf8');
assert(html.includes('id="page-context-menu"'), 'context menu host exists');
for (const action of ['new-tab', 'private-tab', 'copy-link', 'share-link', 'download-link', 'search-text', 'copy-text']) assert(app.includes("'" + action + "'"), 'context action ' + action);
assert(app.includes("addEventListener('contextmenu'"), 'right-click supported');
assert(app.includes("addEventListener('pointerdown'"), 'long press supported');
assert(app.includes('520'), 'long press threshold defined');
assert(app.includes('state.tabs.length >= 12'), 'tab limit enforced');
assert(app.includes('tab.private'));
assert(app.includes('Restore cached Bridge view only — never re-navigate Chromium for a tab switch.'), 'tab switching restores existing session view without reloading');
assert(app.includes('private tabs do not write browsing history'), 'private history suppressed');
assert(app.includes('never Bridge session IDs or authentication tokens'), 'tab restore does not persist bridge credentials');
assert(server.includes('privateMode') && server.includes('randomBytes(12)'), 'private sessions receive unique identity');
assert(bridge.includes('persist: !meta.privateMode'), 'private session persistence disabled at bridge');
assert(engine.includes('opts.persist === false'), 'private session storage disabled in engine');
assert(css.includes('.page-context-menu') && css.includes('.page-context-action'), 'context menu styled');
console.log('Context menu / private tabs / multi-tab regression: PASS');
