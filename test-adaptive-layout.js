'use strict';
const assert = require('assert');
const fs = require('fs');
const engineSource = fs.readFileSync(require.resolve('./lib/engine/playwright-engine'), 'utf8');
const bridge = require('./lib/engine/dom-bridge');
const pkg = require('./package.json');
assert.strictEqual(pkg.version, '10.12.0');
assert.ok(engineSource.includes("process.env.SOLOHOST_BROWSER_CONTENT_MODE || 'adaptive'"), 'adaptive mode is the default');
assert.ok(engineSource.includes("clone.querySelectorAll('[style]')") && engineSource.includes("clone.querySelectorAll('[class]')"), 'classes/inline styles are only stripped inside explicit focused mode');
assert.ok(engineSource.includes("clone.querySelectorAll('video, audio')") && engineSource.includes("mode === 'focused'"), 'video/audio placeholders are opt-in only');
const kept = bridge.sanitizeHtml('<html><head><link rel="stylesheet" href="https://shop.example/site.css"></head><body><main class="product-grid"><h1>Products</h1><iframe src="https://www.youtube.com/embed/abc" title="clip"></iframe><form><input name="q"></form></main></body></html>', 'https://shop.example/products');
assert.ok(kept.includes('class="product-grid"'), 'site layout classes are preserved in bridge sanitizer');
assert.ok(kept.includes('href="https://shop.example/site.css"'), 'site stylesheets are retained to preserve original grid/layout');
assert.ok(kept.includes('youtube.com/embed/abc'), 'allowlisted video embed survives sanitization');
assert.ok(kept.includes('name="q"'), 'form controls survive sanitization');
const blocked = bridge.sanitizeHtml('<html><body><iframe src="https://evil.example/embed">x</iframe><p>Safe text</p></body></html>', 'https://example.com');
assert.ok(!blocked.includes('evil.example'), 'untrusted nested iframe is removed');
assert.ok(blocked.includes('Safe text'), 'normal content remains');
console.log('✓ adaptive layout preserves original form, forms and allowlisted media embeds');
